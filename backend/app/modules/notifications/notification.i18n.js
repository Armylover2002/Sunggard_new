// Built once; any key missing in a language falls back to English.
const TABLES = Object.fromEntries(
  Object.entries(MESSAGES).map(([code, table]) => [code, table]),
);

/**
 * Text for `key` in `lang`, with {placeholders} filled from `vars`.
 * Missing language or key falls back to English, and an unknown key is
 * returned as-is so a bad key is visible rather than blank.
 */
export function translate(lang, key, vars = {}) {
  const code = normalizeLanguage(lang);
  const template = TABLES[code]?.[key] ?? TABLES.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined || vars[name] === null ? "" : String(vars[name]),
  );
}
